export function achievementProgress(a, state) {
  if (state.achievements[a.id]) return a.goal;
  const objective = (mode, key) => state.modes[mode]?.objectives[key] || 0;
  const best = (mode, key) => state.modes[mode]?.bests[key]?.value || 0;
  const values = {
    flawless: Number(!!state.feats?.flawless),
    five: state.feats?.maxKills || 0,
    origins: state.baseWins.length,
    fusion: state.fusionCount,
    tier: state.highestTier > 1 ? state.highestTier : 0,
    forms: state.fusionForms.length,
    master: Object.values(state.mastery).filter(
      (xp) => mastery(xp).level === 20,
    ).length,
    waves: objective("gauntlet", "completions"),
    zombies: best("zombies", "survival"),
    night: objective("corruption", "lightVictories"),
    flags: objective("ctf", "captures"),
    gridiron: objective("gridiron", "victories"),
    race: objective("turnpike", "victories"),
    dungeon: objective("dungeon", "completions"),
    final: objective("dungeon", "finalBoss"),
    ten: state.totals.wins,
    fifty: state.totals.wins,
    six: ORIGINS.filter((e) => mastery(state.mastery[e]).level === 20).length,
  };
  return Math.min(a.goal, values[a.id] || 0);
}
export function cosmeticCatalog() {
  return [
    ...ACHIEVEMENTS.map((a) => ({
      id: a.reward,
      slot: a.slot,
      name: a.rewardName,
      symbol: a.symbol,
      source: a.name,
      tone: ["zombies", "race"].includes(a.id)
        ? "ice"
        : a.id === "tier"
          ? "violet"
          : a.id === "final"
            ? "emerald"
            : "gold",
    })),
    ...FORMS.flatMap((e) =>
      [
        {
          level: 5,
          slot: "badge",
          name: `${nameOf(e)} Bronze`,
          tone: "bronze",
          symbol: "◆",
        },
        {
          level: 10,
          slot: "frame",
          name: `${nameOf(e)} Silver`,
          tone: "silver",
          symbol: "◇",
        },
        {
          level: 15,
          slot: "aura",
          name: `${nameOf(e)} Gold Halo`,
          tone: "gold",
          symbol: "☀",
        },
        {
          level: 20,
          slot: "decoration",
          name: `${nameOf(e)} Master`,
          title: `Master of ${nameOf(e)}`,
          tone: "gold",
          symbol: "✷",
        },
      ].map((c) => ({
        ...c,
        element: e,
        id: `mastery:${e}:${c.level}`,
        source: `${nameOf(e)} mastery Level ${c.level}`,
      })),
    ),
  ];
}
